"""Предложение робота по спорному договору: подсказка оператору, а не решение.

Колонку «Решение» робот не заполняет. Группы «Вопрос …» — случаи, где отнесение к ГрК
зависит от правовой позиции СРО: как только она принята, их можно перевести в правила.
"""
from __future__ import annotations

import re

BUILD = re.compile(r"капитальн\w*\s+ремонт|карпитальн\w*\s+ремонт|капремонт|реконструкц|строительств|"
                   r"строительно-монтаж|\bсмр\b|\bснос")
NOT_WORK = re.compile(r"теплоснабжени|передаче тепловой|редуктор|оклейк|запасных част")
ROADS = re.compile(r"слоев износа|колейност|ремонт\w* (автомобильн|искусственн|шумозащит)")
YARD = re.compile(r"благоустройств|тротуар|пешеходн|игровых|освещени|огражден|стел|брусчат|дорожного покрыт|парка|входной групп")
NETS = re.compile(r"водопровод|канализ|теплов|кабельн|котл|газо|лифт|установки для выработки|пожар|инженерн|автоматик|химводо|сет[иь]\b")
REPAIR = re.compile(r"окон|двер|паркет|покрыти|помещени|кровл|крыш|фасад|ремонт|отделоч|общестроит")


def suggest(subject: str, note: str, status: str) -> tuple[str, str]:
    """(предложение, основание) по предмету, замечанию робота и статусу."""
    t = re.sub(r"\s+", " ", (subject or "").lower().replace("ё", "е"))
    note = note or ""
    if "цена договора 0" in note:
        return "Исключить: дубль или ошибка", "рамочное соглашение, цена 0"
    if "двойник" in note:
        return "Посмотреть", "двойник: оставить один договор из пары"
    if status == "Вероятный":
        return "Ждать ответа члена", "победа по протоколу, договора в ЕИС нет"
    if NOT_WORK.search(t):
        return "Исключить: не по ГрК", "услуга или запчасти, не строительный подряд"
    if BUILD.search(t):
        return "Передать", "в предмете капремонт, реконструкция или строительство"
    if not t:
        return "Посмотреть", "нет предмета договора"
    if ROADS.search(t):
        return "Вопрос: дороги", "ремонт дорог и слои износа"
    if YARD.search(t):
        return "Вопрос: благоустройство", "благоустройство и объекты территории"
    if NETS.search(t):
        return "Вопрос: сети и оборудование", "инженерные сети, лифты, оборудование зданий"
    if REPAIR.search(t):
        return "Вопрос: ремонт", "ремонт без слова «капитальный», окна, двери, кровля"
    return "Посмотреть", "не попал в правила"
